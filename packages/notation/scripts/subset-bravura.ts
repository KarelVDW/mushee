// Writes src/engraving/bravura_glyphs.ts: just the Bravura glyphs listed in GLYPHS, cut from
// the full table in bravura_glyphs.full.ts (445 glyphs, ~250 KB) so the bundles that draw
// notation carry only what they draw. The subset's names are the GlyphName type, so a glyph
// enters the package by being listed here and regenerated:
//
//     pnpm --filter @mushee/notation glyphs:subset
//
// Runs on Node's built-in TypeScript type stripping (Node ≥ 22.18), no build step.

import { writeFileSync } from 'node:fs'

import { BravuraFont } from './bravura_glyphs.full.ts'

type FullGlyphName = keyof typeof BravuraFont.glyphs

/** Every glyph the engraver and the apps' notation icons draw, grouped by role (the output keeps this order). */
const GLYPHS = [
    // Clefs
    'gClef',
    'fClef',
    'cClef',
    // Noteheads
    'noteheadWhole',
    'noteheadHalf',
    'noteheadBlack',
    // Rests
    'restWhole',
    'restHalf',
    'restQuarter',
    'rest8th',
    'rest16th',
    // Flags
    'flag8thUp',
    'flag8thDown',
    'flag16thUp',
    'flag16thDown',
    // Accidentals
    'accidentalSharp',
    'accidentalFlat',
    'accidentalNatural',
    'accidentalDoubleSharp',
    'accidentalDoubleFlat',
    // Time-signature figures (tuplet numbers are set in them too)
    'timeSig0',
    'timeSig1',
    'timeSig2',
    'timeSig3',
    'timeSig4',
    'timeSig5',
    'timeSig6',
    'timeSig7',
    'timeSig8',
    'timeSig9',
] as const satisfies readonly FullGlyphName[]

const OUTPUT = new URL('../src/engraving/bravura_glyphs.ts', import.meta.url)
const INDENT = '    '

/** A TypeScript literal for a table value, quoted the way the repo's Prettier config writes it. */
function literal(value: unknown): string {
    if (typeof value === 'number') return String(value)
    if (typeof value === 'string' && !/['\\\n]/.test(value)) return `'${value}'`
    throw new Error(`subset-bravura: cannot write ${JSON.stringify(value)} as a literal`)
}

function key(name: string): string {
    return /^[A-Za-z_$][\w$]*$/.test(name) ? name : `'${name}'`
}

const { glyphs, ...fontFields } = BravuraFont
const glyphBlocks = GLYPHS.map((name) => {
    const fields = Object.entries(glyphs[name]).map(([field, value]) => `${INDENT.repeat(3)}${key(field)}: ${literal(value)},`)
    return [`${INDENT.repeat(2)}${key(name)}: {`, ...fields, `${INDENT.repeat(2)}},`].join('\n')
})
const lines = [
    '// Generated by scripts/subset-bravura.ts from scripts/bravura_glyphs.full.ts — do not edit.',
    '// The Bravura glyphs this package draws; to add one, list it in that script and rerun it.',
    '',
    'export const BravuraFont = {',
    `${INDENT}glyphs: {`,
    ...glyphBlocks,
    `${INDENT}},`,
    ...Object.entries(fontFields).map(([field, value]) => `${INDENT}${key(field)}: ${literal(value)},`),
    '}',
    '',
]

writeFileSync(OUTPUT, lines.join('\n'))
console.log(`subset-bravura: wrote ${GLYPHS.length} of ${Object.keys(glyphs).length} glyphs to ${OUTPUT.pathname}`)
